const assert = require('node:assert/strict');
const core = require('../src/editor-core');
const original = '{"item10":900719925474099312345,"item2":1.0000000000000000001,"same":1,"same":2,"text":"中文\\n🙂"}';
const pretty = core.formatJSON(original);
assert.match(pretty, /900719925474099312345/);
assert.match(pretty, /1\.0000000000000000001/);
assert.equal((pretty.match(/"same"/g) || []).length, 2);
assert.equal(core.formatJSON(pretty, 'compact'), original);
const sorted = core.formatJSON(original, 'sort');
assert.ok(sorted.indexOf('item2') < sorted.indexOf('item10'));
assert.equal(core.formatJSON(core.formatJSON(original, 'escape'), 'unescape'), original);
assert.equal(core.formatJSON('hello\\nworld', 'unescape'), 'hello\nworld');
assert.throws(() => core.formatJSON('{"a":1,}'));
assert.throws(() => core.formatJSON('[01]'));
assert.throws(() => core.formatJSON('true false'));
assert.throws(() => core.formatJSON('"\\q"'));
assert.throws(() => core.formatJSON('['.repeat(514) + '0' + ']'.repeat(514)), /512/);
const sample = '{\n  "text":"braces {} []",\n  "list":[\n    {\n      "x":1\n    }\n  ]\n}';
assert.equal(core.parseJSON(sample).regions.length, 3);
assert.equal(core.findMatches('ab ab AB', 'ab').matches.length, 3);
assert.equal(core.findMatches('ab ab AB', 'ab', true).matches.length, 2);
assert.equal(core.findMatches('a'.repeat(10005), 'a').limited, true);
assert.equal(core.findMatches('a.b a*b', 'a.b').matches.length, 1);
assert.equal(core.formatConfiguration('password = secret  ').text, 'password=secret  ');
assert.equal(core.formatConfiguration('first\\=last = value  ').text, 'first\\=last=value  ');
assert.throws(() => core.formatConfiguration('a = first\\\nsecond'), /Properties|YAML/);
assert.throws(() => core.formatConfiguration('a: 1\na: 2'));
assert.throws(() => core.formatConfiguration('a: |\n  contents'));
assert.equal(core.formatConfiguration('server:\n    port: 8080\n    enabled: true').text, 'server:\n  port: 8080\n  enabled: true');
assert.match(core.formatSQL("select N'文字', count(*) from users where id = 1;"), /N'文字'/);
assert.match(core.formatSQL('select a,b from t'), /^SELECT\n  a,\n  b\nFROM t$/);
assert.throws(() => core.formatSQL("select E'escaped\\n'"));
assert.throws(() => core.formatSQL('select $$body$$'));
assert.throws(() => core.formatSQL('select [column]'));
assert.throws(() => core.formatSQL("select 'a' 'b'"));
assert.throws(() => core.formatSQL('select ((a)'));
assert.match(core.formatSQL('select a -- comment\nfrom t'), /-- comment\nFROM t/);
console.log('编辑器核心检查通过：JSON 数字与顺序保真、折叠范围、搜索限额、YAML/Properties 与 SQL 安全边界');
