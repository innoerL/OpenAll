const assert = require('node:assert/strict');
const b = require('../src/backend');
const changes=b.configDiff('password: old\nserver:\n  port: 80','password: new\nserver:\n  port: 81','yaml');
assert.equal(changes.find(x=>x.key==='password').left,'••••••');
assert.equal(changes.find(x=>x.key==='server.port').right,'81');
assert.throws(()=>b.configDiff('a: 1\na: 2','a: 3','yaml'));
assert.equal(b.configDiff('{"a":1}','{"a":1}','json').length,0);
const restored=b.restoreSQL("SELECT '?' AS q, id FROM t WHERE a=? AND b=:name AND c=$2 -- ?\n",["O'Reilly",42]);
assert.match(restored.sql,/a='O''Reilly'/);
assert.match(restored.sql,/c=42/);
assert.deepEqual(restored.missing,[':name']);
assert.match(restored.sql,/-- \?/);
assert.equal(b.restoreSQL('x=:id::int',{id:3}).sql,'x=3::int');
const prefix = "SELECT '💎', 42, ", secondPrefix = prefix + "42, $tag$? 42$tag$, /* ? */ ";
const marked = b.restoreSQL(prefix + "?, $tag$? 42$tag$, /* ? */ $1, :missing", [42]);
assert.deepEqual(marked.replacementRanges, [{from:prefix.length,to:prefix.length+2},{from:secondPrefix.length,to:secondPrefix.length+2}]);
const logs=b.parseLogs('{"time":"2026-01-02","service":"api"}\nservice=api time=2026-01-01\nplain line');
assert.equal(b.logFields(logs).find(x=>x.key==='service').count,2);
assert.equal(b.logGroups(logs,'service','time')[0].entries[0].fields.time,'2026-01-01');
assert.ok(b.explain('[{"Plan":{"Node Type":"Seq Scan","Relation Name":"t"}}]')[0].warning);
assert.ok(b.explain('{"query_block":{"table":{"table_name":"users","access_type":"ALL"}}}')[0].warning);
console.log('Windows 后端工具样例检查通过');
