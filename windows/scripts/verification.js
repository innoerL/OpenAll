const fs = require('node:fs');
const { execFileSync } = require('node:child_process');
const read = file => JSON.parse(fs.readFileSync(file, 'utf8').replace(/^\uFEFF/, ''));
const installed = read('artifacts/installer-report.json');
const tools = read('artifacts/screens/report.json');
const indexing = read('artifacts/native-file-search/report.json');
if (!installed.installed || !installed.checksPassed || !installed.uninstalled || !tools.passed || tools.platform !== 'win32' || !indexing.passed || !indexing.systemIndex?.available) throw Error('完整 Windows 验收尚未通过');
const gold = read('artifacts/gold/report.json');
if (!gold.passed || gold.platform !== 'win32') throw Error('Windows 金价内置窗口尚未通过');
const status = read('docs/parity-status.json');
status.verifiedVersion = read('package.json').version;
status.parityComplete = true;
status.note = '保留原有功能对齐基线；金价改为 OpenAll 内置工具，使用宿主窗口、外观和生命周期，已通过真实 Windows 功能及安装包回归。字体光栅化、系统弹窗与平台接口仍有系统差异。';
status.features = status.features.map(feature => ({ ...feature, status: 'verified_windows' }));
status.remaining = [];
status.verification = { commit: execFileSync('git', ['rev-parse', 'HEAD'], { encoding: 'utf8' }).trim(), run: process.env.GITHUB_RUN_ID, checks: tools.checks.length, screenshots: tools.screenshots.length, performance: tools.performance, systemIndex: indexing.systemIndex, installed: true, uninstalled: true, gold: { checks: gold.checks.length, screenshots: gold.screenshots.length } };
status.platformBoundaries = ['Ctrl 对应 Cmd，资源管理器对应访达；文件快速预览使用默认应用。', '系统文件索引仅覆盖已索引位置，另有 KnownFolders 目录扫描回退。', 'OCR 依赖已安装语言包；自动粘贴受目标应用权限级别限制。', '有道翻译依赖网络；加载失败保留重试与浏览器打开。', '安装器未代码签名；更新源默认空，下载校验 SHA-256。', '金价 CI 使用隔离离线样例；实时行情及新闻日历服务可用性依赖网络。'];
fs.writeFileSync('docs/parity-status.json', JSON.stringify(status, null, 2) + '\n');
